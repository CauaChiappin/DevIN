    const translate = (value) => {
        const text = String(value);
        const trimmed = text.trim();
        const translated = translations[language][trimmed];
        if (translated) return text.replace(trimmed, translated);

        const countMatch = trimmed.match(/^(\d+) (candidatos|vagas|posts|registros)$/i);
        if (countMatch) {
            const count = Number(countMatch[1]);
            const labels = language === 'en'
                ? { candidatos: count === 1 ? 'candidate' : 'candidates', vagas: count === 1 ? 'job' : 'jobs', posts: count === 1 ? 'post' : 'posts', registros: count === 1 ? 'record' : 'records' }
                : { candidatos: count === 1 ? 'candidato' : 'candidatos', vagas: count === 1 ? 'empleo' : 'empleos', posts: count === 1 ? 'publicación' : 'publicaciones', registros: count === 1 ? 'registro' : 'registros' };
            return text.replace(trimmed, `${count} ${labels[countMatch[2].toLowerCase()]}`);
        }
        const liveSubtitle = trimmed.match(/^(Pessoa|Empresa) · Atualização automática$/);
        let result = liveSubtitle
            ? text.replace(trimmed, `${translations[language][liveSubtitle[1]]} · ${translations[language]['Atualização automática']}`)
            : text;

        const unreadNotice = trimmed.match(/^Nova mensagem de (.+)\. (\d+) mensagens não lidas\.$/);
        const unreadCount = trimmed.match(/^(\d+) mensagens não lidas$/);
        if (unreadNotice) {
            const message = language === 'en'
                ? `New message from ${unreadNotice[1]}. ${unreadNotice[2]} unread messages.`
                : `Nuevo mensaje de ${unreadNotice[1]}. ${unreadNotice[2]} mensajes sin leer.`;
            result = text.replace(trimmed, message);
        } else if (unreadCount) {
            const label = language === 'en' ? 'unread messages' : 'mensajes sin leer';
            result = text.replace(trimmed, `${unreadCount[1]} ${label}`);
        }

        const embeddedLabels = language === 'en'
            ? [['E-mail:', 'Email:'], ['CPF:', 'CPF:'], ['CNPJ', 'Company ID'], ['Escolaridade:', 'Education:'], ['Candidatura para ', 'Application for '], ['Status ', 'Status '], ['Experiência profissional', 'Work experience'], ['Candidatura::', 'Application::'], ['Publicação::', 'Posted::'], ['Perfil DevIN::', 'DevIN profile::'], ['Candidato para ', 'Candidate for '], ['Vaga publicada por ', 'Job posted by ']]
            : [['E-mail:', 'Correo:'], ['CPF:', 'CPF:'], ['CNPJ', 'NIF'], ['Escolaridade:', 'Educación:'], ['Candidatura para ', 'Postulación para '], ['Status ', 'Estado '], ['Experiência profissional', 'Experiencia profesional'], ['Candidatura::', 'Postulación::'], ['Publicação::', 'Publicado::'], ['Perfil DevIN::', 'Perfil de DevIN::'], ['Candidato para ', 'Candidato para '], ['Vaga publicada por ', 'Empleo publicado por ']];
        embeddedLabels.forEach(([source, target]) => {
            result = result.replaceAll(source, target);
        });
        return result;
    };

