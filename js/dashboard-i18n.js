    document.title = translate(document.title);
    const translateTree = (root) => {
        if (root.nodeType === Node.TEXT_NODE) {
            root.nodeValue = translate(root.nodeValue);
            return;
        }

        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) node.nodeValue = translate(node.nodeValue);

        const elements = root.nodeType === Node.ELEMENT_NODE ? [root, ...root.querySelectorAll('*')] : [...root.childNodes];
        elements.forEach((element) => {
            if (element.nodeType !== Node.ELEMENT_NODE) return;
            ['placeholder', 'aria-label', 'title', 'alt', 'data-confirm-logout', 'data-detail-action-label'].forEach((attribute) => {
                if (element.hasAttribute(attribute)) element.setAttribute(attribute, translate(element.getAttribute(attribute)));
            });
        });
    };

    translateTree(document.body);
    new MutationObserver((records) => {
        records.forEach((record) => record.addedNodes.forEach((node) => {
            if (node.nodeType === Node.ELEMENT_NODE || node.nodeType === Node.TEXT_NODE) translateTree(node);
        }));
    }).observe(document.body, { childList: true, subtree: true });
