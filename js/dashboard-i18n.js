    const dictionary = translations[language];
    const translate = (value) => {
        const original = String(value ?? '');
        if (!dictionary) return original;
        const trimmed = original.trim();
        let translated = dictionary[trimmed];

        if (translated === undefined) {
            const count = trimmed.match(/^(\d+)\s+(vagas|candidatos)$/i);
            if (count) {
                const noun = count[2].toLocaleLowerCase('pt-BR');
                translated = language === 'en'
                    ? `${count[1]} ${noun === 'vagas' ? 'jobs' : 'candidates'}`
                    : `${count[1]} ${noun === 'vagas' ? 'empleos' : 'candidatos'}`;
            }
        }

        if (translated === undefined) {
            const unread = trimmed.match(/^(\d+)\s+mensagens não lidas$/i);
            if (unread) {
                translated = language === 'en'
                    ? `${unread[1]} unread messages`
                    : `${unread[1]} mensajes sin leer`;
            }
        }

        if (translated === undefined && trimmed.includes('|')) {
            translated = trimmed.split('|').map((part) => dictionary[part] ?? part).join('|');
        }

        if (translated === undefined && trimmed.includes('::')) {
            translated = trimmed.split('::').map((part) => dictionary[part] ?? part).join('::');
        }

        if (translated === undefined) {
            const detailPrefix = trimmed.match(/^(Candidato para|Candidatura para)\s+(.+)$/);
            if (detailPrefix) {
                translated = `${dictionary[detailPrefix[1]]} ${detailPrefix[2]}`;
            }
        }

        if (translated === undefined) {
            const status = trimmed.match(/^Status\s+(aprovado|aprovada|recusado|recusada|pendente)$/i);
            if (status) {
                translated = `${dictionary.Status} ${dictionary[status[1].charAt(0).toUpperCase() + status[1].slice(1)] ?? status[1]}`;
            }
        }

        if (translated === undefined) return original;
        const leadingWhitespace = original.match(/^\s*/)?.[0] ?? '';
        const trailingWhitespace = original.match(/\s*$/)?.[0] ?? '';
        return `${leadingWhitespace}${translated}${trailingWhitespace}`;
    };

    window.DevINTranslate = translate;

    if (!dictionary) return;

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
        if (node.parentElement?.closest('script, style, textarea, input')) continue;
        node.nodeValue = translate(node.nodeValue);
    }

    document.querySelectorAll('*').forEach((element) => {
        for (const attribute of ['placeholder', 'aria-label', 'title', 'data-confirm-logout', 'data-detail', 'data-detail-role', 'data-detail-tags', 'data-detail-experience', 'data-detail-action-label', 'data-detail-meta']) {
            if (element.hasAttribute(attribute)) {
                element.setAttribute(attribute, translate(element.getAttribute(attribute)));
            }
        }
    });
